class DAPError(RuntimeError):
    """SWD, target, or firmware programming failure."""


def _parity(value):
    value ^= value >> 16
    value ^= value >> 8
    value ^= value >> 4
    return (0x6996 >> (value & 15)) & 1


class SWD:
    """PIO SWD, using single-cycle turnaround and bounded WAIT retries.

    frequency is the SWCLK burst rate. Python introduces clock-low gaps
    between PIO commands; no GPIO edges are generated by the interpreter.
    """

    def __init__(self, swclk, swdio, *, frequency=1000000, retries=100, timeout=2):
        if swclk == swdio:
            raise ValueError("SWCLK and SWDIO must be different pins")
        if not 1000 <= frequency <= 10000000 or retries < 1 or timeout <= 0:
            raise ValueError("Invalid SWD timing")
        import rp2pio
        import adafruit_pioasm

        self.retries = retries
        self.timeout = timeout
        self._select = None
        self._tx = array("I", [0, 0])
        self._rx = array("I", [0])
        self._command = memoryview(self._tx)[:1]
        # Commands: count-1 in bits 0..4, input flag in bit 5. Output
        # commands have a second word containing LSB-first pin data.
        # Both loops take four PIO cycles per SWCLK period. FIFO stalls
        # and command decoding always park SWCLK low.
        code = adafruit_pioasm.assemble("""
.side_set 1
.wrap_target
    pull block side 0
    out x, 5 side 0
    out y, 1 side 0
    jmp !y write side 0
    set pindirs, 0 side 0
read:
    in pins, 1 side 1 [1]
    jmp x-- read side 0 [1]
    push block side 0
    jmp done side 0
write:
    pull block side 0
    set pindirs, 1 side 0
bits:
    out pins, 1 side 0 [1]
    jmp x-- bits side 1 [1]
    mov isr, null side 0
    push block side 0
done:
    nop side 0
.wrap
""")
        self._sm = rp2pio.StateMachine(
            code, frequency=int(frequency * 4),
            first_out_pin=swdio, out_pin_count=1,
            first_in_pin=swdio, in_pin_count=1,
            first_set_pin=swdio, set_pin_count=1,
            first_sideset_pin=swclk, sideset_pin_count=1,
            initial_out_pin_state=1, initial_out_pin_direction=1,
            initial_set_pin_state=1, initial_set_pin_direction=1,
            initial_sideset_pin_state=0, initial_sideset_pin_direction=1,
            out_shift_right=True, in_shift_right=True,
            auto_pull=False, auto_push=False,
            wait_for_txstall=False,
        )

    def deinit(self):
        """Release the PIO state machine and both pins."""
        if self._sm is not None:
            self._sm.deinit()
            self._sm = None

    def _out(self, value, count):
        while count:
            chunk = min(count, 32)
            self._tx[0] = chunk - 1
            self._tx[1] = value & 0xFFFFFFFF
            self._sm.write_readinto(self._tx, self._rx)
            count -= chunk
            value >>= chunk

    def _in(self, count):
        value = 0
        shift = 0
        while count:
            chunk = min(count, 32)
            self._tx[0] = 0x20 | (chunk - 1)
            self._sm.write_readinto(self._command, self._rx)
            value |= (self._rx[0] >> (32 - chunk)) << shift
            count -= chunk
            shift += chunk
        return value

    def line_reset(self):
        self._out((1 << 56) - 1, 56)

    def connect(self):
        """Wait for SWD startup, clear errors, and request debug/system power."""
        deadline = time.monotonic() + self.timeout
        while True:
            try:
                self.line_reset()
                self._out(0xE79E, 16)
                self.line_reset()
                self._out(0, 8)
                identity = self.read_dp(0)
                if identity in (0, 0xFFFFFFFF) or not identity & 1:
                    raise DAPError("Invalid SWD DPIDR: 0x%08x" % identity)
                self.write_dp(0, 0x1E)
                self.write_dp(8, 0)
                self.write_dp(4, 0x50000000)
                while self.read_dp(4) & 0xA0000000 != 0xA0000000:
                    if time.monotonic() >= deadline:
                        raise DAPError("Debug power-up timed out")
                return identity
            except DAPError as error:
                if time.monotonic() >= deadline:
                    raise DAPError("SWD connection timed out: %s" % error)
                # Power/reset can outlast both ID reads and initial DP writes.
                # These debug setup writes are idempotent; flash is untouched.
                self._select = None
                time.sleep(0.01)

    def transfer(self, ap, read, address, value=0):
        """Transfer one DP/AP register; AP reads are posted."""
        request = int(bool(ap)) | (int(bool(read)) << 1) | (address & 12)
        header = 0x81 | (request << 1) | (_parity(request) << 5)
        deadline = time.monotonic() + self.timeout
        for _ in range(self.retries):
            self._out(header, 8)
            ack = self._in(4) >> 1  # Released turnaround, then three ACK bits.
            if ack == 1:
                if read:
                    result = self._in(32)
                    parity = self._in(2) & 1  # Parity, then released turnaround.
                else:
                    self._in(1)
                    self._out(value, 32)
                    self._out(_parity(value), 1)
                    result = 0
                    parity = 0
                self._out(0, 8)
                if read and parity != _parity(result):
                    raise DAPError("SWD read parity error")
                return result
            self._in(1 if ack in (2, 4) else 34)
            self._out(0, 8)
            if ack == 4:
                raise DAPError("SWD FAULT; reconnect to clear sticky errors")
            if ack != 2:
                raise DAPError("Invalid SWD ACK 0x%x; check wiring and power" % ack)
            if time.monotonic() >= deadline:
                break
        raise DAPError("SWD WAIT timed out")

    def read_dp(self, address):
        return self.transfer(False, True, address)

    def write_dp(self, address, value):
        self.transfer(False, False, address, value)
        if address == 8:
            self._select = value

    def _select_ap(self, address, apsel):
        selection = (apsel << 24) | (address & 0xF0)
        if self._select != selection:
            self.write_dp(8, selection)

    def read_ap(self, address, apsel=0):
        self._select_ap(address, apsel)
        self.transfer(True, True, address)
        return self.read_dp(12)

    def write_ap(self, address, value, apsel=0):
        self._select_ap(address, apsel)
        self.transfer(True, False, address, value)
        self.read_dp(12)  # Drain the posted write and surface bus errors.


class ARMTarget:
    """AHB-AP memory access and Cortex-M core control (APSEL defaults to zero)."""

    def __init__(self, swd, apsel=0, reset_callback=None):
        self.swd = swd
        self.apsel = apsel
        self._reset_callback = reset_callback
        self._csw = None
        self._tar = None

    def read32(self, address):
        return self._memory(address, 2, True)

    def write32(self, address, value):
        self._memory(address, 2, False, value)

    def write16(self, address, value):
        self._memory(address, 1, False, value << ((address & 2) * 8))

    def write8(self, address, value):
        self._memory(address, 0, False, value << ((address & 3) * 8))

    def _memory(self, address, size, read, value=0):
        if address < 0 or address > 0xFFFFFFFF or address % (1 << size):
            raise ValueError("Unaligned or out-of-range memory address")
        try:
            csw = 0x23000050 | size  # Single increment, with 1 KiB TAR wrap.
            if self._csw != csw:
                self.swd.write_ap(0, csw, self.apsel)
                self._csw = csw
            if self._tar != address:
                self.swd.write_ap(4, address, self.apsel)
            if read:
                result = self.swd.read_ap(12, self.apsel)
            else:
                self.swd.write_ap(12, value, self.apsel)
                result = None
            self._tar = (address & ~0x3FF) | ((address + (1 << size)) & 0x3FF)
            return result
        except BaseException:
            self._csw = None
            self._tar = None
            raise

    def wait(self, address, mask, expected, timeout=2):
        deadline = time.monotonic() + timeout
        while True:
            value = self.read32(address)
            if value & mask == expected:
                return value
            if time.monotonic() >= deadline:
                raise DAPError("Target timed out at 0x%08x" % address)

    def halt(self):
        self.write32(0xE000EDF0, 0xA05F0003)
        self.wait(0xE000EDF0, 0x20000, 0x20000)

    def reset(self):
        """Release core halt and reset using nRESET, or AIRCR if unwired."""
        try:
            self.write32(0xE000EDF0, 0xA05F0001)
            if self._reset_callback is not None:
                self._reset_callback()
            else:
                self.write32(0xE000ED0C, 0x05FA0004)
        finally:
            self._csw = None
            self._tar = None


class FlashTarget:
    """Base for target drivers. Erases operate on complete pages/rows.

    Drivers implement probe(), erase_page(address), write(address, data),
    and optionally begin()/finish(). A failed operation leaves the core halted.
    """

    flash_start = 0
    flash_size = 0
    page_size = 0
    write_size = 4

    def __init__(self, arm):
        self.arm = arm

    def probe(self):
        raise NotImplementedError

    def begin(self):
        pass

    def attach(self):
        self.arm.halt()

    def release_reset(self):
        pass

    def finish(self):
        pass

    def erase_page(self, address):
        raise NotImplementedError

    def write(self, address, data):
        raise NotImplementedError


class NRF52(FlashTarget):
    """nRF52832 and nRF52840 main flash; UICR is excluded."""

    page_size = 4096

    def probe(self):
        part = self.arm.read32(0x10000100)
        if part not in (0x52832, 0x52840):
            raise DAPError("Target is not a supported nRF52")
        self.part = part
        self.flash_size = self.arm.read32(0x10000014) * self.arm.read32(0x10000010)
        if self.arm.read32(0x10000010) != self.page_size or not 0 < self.flash_size <= 1048576:
            raise DAPError("Invalid nRF52 flash geometry")

    def _mode(self, value):
        self.arm.wait(0x4001E400, 1, 1)
        self.arm.write32(0x4001E504, value)
        self.arm.wait(0x4001E400, 1, 1)

    def erase_page(self, address):
        self._mode(2)
        self.arm.write32(0x4001E508, address)
        self.arm.wait(0x4001E400, 1, 1)

    def write(self, address, data):
        self._mode(1)
        for offset in range(0, len(data), 4):
            self.arm.write32(address + offset, int.from_bytes(data[offset:offset + 4], "little"))
            self.arm.wait(0x4001E400, 1, 1)

    def finish(self):
        self._mode(0)


class STM32F1(FlashTarget):
    """STM32F103 low/medium density, 1 KiB pages, main flash only."""

    flash_start = 0x08000000
    page_size = 1024
    write_size = 2

    def probe(self):
        if self.arm.read32(0xE0042000) & 0xFFF not in (0x410, 0x412):
            raise DAPError("Target is not a low/medium-density STM32F1")
        self.flash_size = (self.arm.read32(0x1FFFF7E0) & 0xFFFF) * 1024
        if not 0 < self.flash_size <= 131072:
            raise DAPError("Unsupported STM32F1 flash geometry")

    def begin(self):
        if self.arm.read32(0x40022010) & 0x80:
            self.arm.write32(0x40022004, 0x45670123)
            self.arm.write32(0x40022004, 0xCDEF89AB)
        if self.arm.read32(0x40022010) & 0x80:
            raise DAPError("STM32 flash is locked")
        self.arm.write32(0x4002200C, 0x34)

    def _ready(self):
        status = self.arm.wait(0x4002200C, 1, 0)
        if status & 0x14:
            raise DAPError("STM32 flash error: 0x%x" % status)

    def erase_page(self, address):
        self._ready()
        self.arm.write32(0x40022010, 2)
        self.arm.write32(0x40022014, address)
        self.arm.write32(0x40022010, 0x42)
        self._ready()

    def write(self, address, data):
        self.arm.write32(0x40022010, 1)
        for offset in range(0, len(data), 2):
            self.arm.write16(address + offset, int.from_bytes(data[offset:offset + 2], "little"))
            self._ready()

    def finish(self):
        self.arm.write32(0x40022010, 0x80)


class SAMD21(FlashTarget):
    """SAMD21 main flash, 64-byte pages and 256-byte erase rows."""

    page_size = 256
    write_size = 64
    device_family = 0x1001
    max_flash_size = 262144
    device_name = "SAMD21"

    def release_reset(self):
        # STATUSA.CRSTEXT is W1C. Byte access avoids changing CTRL/STATUSB.
        self.arm.write8(0x41002101, 2)

    def attach(self):
        self.arm.write32(0xE000EDF0, 0xA05F0003)
        self.release_reset()
        self.arm.halt()

    def probe(self):
        if self.arm.read32(0x41002118) >> 16 != self.device_family:
            raise DAPError("Target is not a %s" % self.device_name)
        param = self.arm.read32(0x41004008)
        if (8 << ((param >> 16) & 7)) != 64:
            raise DAPError("Unsupported %s page size" % self.device_name)
        self.flash_size = (param & 0xFFFF) * 64
        if not 0 < self.flash_size <= self.max_flash_size:
            raise DAPError("Unsupported %s flash size" % self.device_name)

    def _ready(self):
        self.arm.wait(0x41004014, 1, 1)
        if self.arm.read32(0x41004018) & 0x1C:
            raise DAPError("%s NVM error or locked region" % self.device_name)

    def _command(self, command):
        self.arm.write16(0x41004000, 0xA500 | command)
        self._ready()

    def begin(self):
        self._ready()
        self._ctrlb = self.arm.read32(0x41004004)
        self.arm.write32(0x41004004, self._ctrlb | 0x80)  # Manual page write.

    def erase_page(self, address):
        self.arm.write32(0x4100401C, address >> 1)
        self._command(2)

    def write(self, address, data):
        for offset in range(0, len(data), 64):
            self._command(0x44)  # Clear page buffer.
            for word in range(0, 64, 4):
                self.arm.write32(address + offset + word,
                                 int.from_bytes(data[offset + word:offset + word + 4], "little"))
            self.arm.write32(0x4100401C, (address + offset) >> 1)
            self._command(4)

    def finish(self):
        self.arm.write32(0x41004004, self._ctrlb)


class SAMD11(SAMD21):
    """SAMD11 main flash, 64-byte pages and 256-byte erase rows."""

    device_family = 0x1003
    max_flash_size = 16384
    device_name = "SAMD11"


TARGETS = {"samd11": SAMD11, "nrf52": NRF52, "nrf52832": NRF52, "nrf52840": NRF52,
           "stm32f1": STM32F1, "stm32f103": STM32F1, "samd21": SAMD21}


def register_target(name, driver):
    """Register a FlashTarget subclass under an explicit target name."""
    TARGETS[name.lower()] = driver


def _segments(filename, base_address):
    """Stream binary or Intel HEX; at most one record/chunk is held in RAM."""
    if not filename.lower().endswith((".hex", ".ihex")):
        with open(filename, "rb") as source:
            address = base_address
            while True:
                data = source.read(256)
                if not data:
                    return
                yield address, data
                address += len(data)
        return
    upper = 0
    eof = False
    with open(filename, "r") as source:
        for number, line in enumerate(source, 1):
            line = line.strip()
            if not line:
                continue
            if eof or not line.startswith(":") or len(line) > 521:
                raise ValueError("Invalid HEX record on line %d" % number)
            try:
                record = bytes.fromhex(line[1:])
            except ValueError:
                raise ValueError("Invalid HEX digits on line %d" % number)
            if len(record) < 5 or len(record) != record[0] + 5 or sum(record) & 255:
                raise ValueError("Invalid HEX length/checksum on line %d" % number)
            count, kind = record[0], record[3]
            address = (record[1] << 8) | record[2]
            data = record[4:-1]
            if kind == 0:
                if address + count > 65536:
                    raise ValueError("HEX record crosses a 64 KiB boundary")
                if count:
                    yield upper + address, data
            elif kind == 1 and count == 0 and address == 0:
                eof = True
            elif kind in (2, 4) and count == 2 and address == 0:
                upper = int.from_bytes(data, "big") << (4 if kind == 2 else 16)
            elif kind in (3, 5) and count == 4 and address == 0:
                pass  # Entry point metadata; reset uses the target vector table.
            else:
                raise ValueError("Unsupported or malformed HEX record")
    if not eof:
        raise ValueError("HEX file is missing EOF")


class Programmer:
    """Owns pins and programs main flash from .bin or Intel .hex files.

    target is an explicit registered name or None for identification. erase
    always erases entire touched rows/pages, including bytes outside the image.
    """

    def __init__(self, swclk, swdio, target=None, *, reset_pin=None,
                 reset_hold=0.01, reset_delay=0.01, **kwargs):
        if target is not None and target.lower() not in TARGETS:
            raise ValueError("Unknown target: %s" % target)
        if reset_pin is not None and reset_pin in (swclk, swdio):
            raise ValueError("Reset pin must differ from SWCLK and SWDIO")
        if reset_hold <= 0 or reset_delay < 0:
            raise ValueError("Invalid reset timing")
        self.target_name = target.lower() if target is not None else None
        self._reset_pin = None
        self._reset_hold = reset_hold
        self._reset_delay = reset_delay
        self.swd = SWD(swclk, swdio, **kwargs)
        try:
            if reset_pin is not None:
                import digitalio

                self._reset_pin = digitalio.DigitalInOut(reset_pin)
                self._reset_pin.switch_to_output(
                    value=True, drive_mode=digitalio.DriveMode.OPEN_DRAIN)
        except BaseException:
            self.deinit()
            raise
        self.arm = ARMTarget(self.swd, reset_callback=(
            self.hardware_reset if reset_pin is not None else None))
        self.target = None

    def __enter__(self):
        return self

    def __exit__(self, *_):
        self.deinit()

    def deinit(self):
        """Release nRESET, the PIO state machine, and all owned pins."""
        try:
            if self._reset_pin is not None:
                try:
                    self._reset_pin.value = True
                finally:
                    self._reset_pin.deinit()
                    self._reset_pin = None
        finally:
            self.swd.deinit()

    def hardware_reset(self):
        """Pulse nRESET; reconnect SWD and release reset holds for a known target.

        The target must provide a pull-up. Before connect(), the raw pulse
        requires no working SWD connection. This does not clear a
        debugger's core-halt request; arm.reset() releases halt before pulsing.
        """
        if self._reset_pin is None:
            raise ValueError("No reset pin configured")
        try:
            self._reset_pin.value = False
            time.sleep(self._reset_hold)
        finally:
            self._reset_pin.value = True
            self.swd._select = None
            self.arm._csw = None
            self.arm._tar = None
        time.sleep(self._reset_delay)
        if self.target is not None:
            self.swd.connect()
            self.target.release_reset()

    def connect(self):
        self.target = None
        self.arm._csw = None
        self.arm._tar = None
        identity = self.swd.connect()
        if self.target_name is None:
            # CPUID narrows identification to safe, implemented memory maps.
            core = (self.arm.read32(0xE000ED00) >> 4) & 0xFFF
            if core == 0xC60:  # Cortex-M0+: distinguish supported SAM D families.
                family = self.arm.read32(0x41002118) >> 16
                driver = {0x1001: SAMD21, 0x1003: SAMD11}.get(family)
                if driver is None:
                    raise DAPError("Unsupported SAM D family: 0x%04x" % family)
            elif core == 0xC23:  # Cortex-M3: STM32F1 candidate.
                driver = STM32F1
            elif core == 0xC24:  # Cortex-M4: nRF52 candidate.
                driver = NRF52
            else:
                raise DAPError("No automatic target match; specify a registered driver")
        else:
            driver = TARGETS[self.target_name]
        target = driver(self.arm)
        target.probe()
        target.attach()
        if self.target_name in ("nrf52832", "nrf52840"):
            if target.part != int(self.target_name[3:], 16):
                raise DAPError("Connected nRF52 does not match requested part")
        self.target = target
        return identity

    def program(self, filename, *, address=None, verify=True, reset=True, progress=None,
                status=None):
        """Program an image, returning its byte count.

        address applies only to binary files. progress(done, total) runs after
        each segment. Records must be ordered and non-overlapping. The file
        must remain unchanged throughout this call. Verification is readback.
        status(stage, done, total) reports connect/erase/program/verify/reset/
        complete stages. Programming status counts image bytes committed to flash.
        """
        if self.target is None:
            if status is not None:
                status("connect", 0, 0)
            self.connect()
        target = self.target
        base = target.flash_start if address is None else address
        if address is not None and filename.lower().endswith((".hex", ".ihex")):
            raise ValueError("HEX contains addresses; omit address")
        pages = set()
        total = 0
        end = target.flash_start
        for start, data in _segments(filename, base):
            stop = start + len(data)
            if start < end or stop > target.flash_start + target.flash_size:
                raise ValueError("Image outside main flash, overlapping, or unordered")
            end = stop
            total += len(data)
            page = start - (start % target.page_size)
            while page < stop:
                pages.add(page)
                page += target.page_size
        if not total:
            raise ValueError("Firmware file is empty")
        self.arm.halt()
        target.begin()
        try:
            if status is not None:
                status("erase", 0, len(pages))
            for page_index, page in enumerate(sorted(pages)):
                target.erase_page(page)
                if status is not None:
                    status("erase", page_index + 1, len(pages))
            # Coalesce sparse records into programming units so no unit is
            # programmed twice (important for page-buffer based controllers).
            pending = None
            buffer = None
            done = 0
            committed = 0
            pending_count = 0
            unit = target.write_size
            if status is not None:
                status("program", 0, total)
            for start, data in _segments(filename, base):
                for offset, byte in enumerate(data):
                    location = start + offset
                    aligned = location - location % unit
                    if pending != aligned:
                        if pending is not None:
                            target.write(pending, buffer)
                            committed += pending_count
                        pending = aligned
                        pending_count = 0
                        buffer = bytearray(b"\xff" * unit)
                    buffer[location - aligned] = byte
                    pending_count += 1
                done += len(data)
                if status is not None:
                    status("program", committed, total)
                if progress is not None:
                    progress(done, total)
            if pending is not None:
                target.write(pending, buffer)
                committed += pending_count
            if status is not None:
                status("program", committed, total)
        finally:
            target.finish()
        if verify:
            if status is not None:
                status("verify", 0, total)
            verified = 0
            cached_address = None
            cached = 0
            for start, data in _segments(filename, base):
                for offset, expected in enumerate(data):
                    location = start + offset
                    aligned = location & ~3
                    if cached_address != aligned:
                        cached = self.arm.read32(aligned)
                        cached_address = aligned
                    if (cached >> ((location & 3) * 8)) & 255 != expected:
                        raise DAPError("Readback mismatch at 0x%08x" % location)
                verified += len(data)
                if status is not None:
                    status("verify", verified, total)
        if reset:
            if status is not None:
                status("reset", 0, 1)
            self.arm.reset()
            if status is not None:
                status("reset", 1, 1)
        if status is not None:
            status("complete", total, total)
        return total


def program(swclk, swdio, filename, target=None, *, reset_pin=None,
            reset_hold=0.01, reset_delay=0.01, address=None,
            verify=True, reset=True, progress=None, status=None, **kwargs):
    """Program a file and release pins, including when an exception occurs."""
    with Programmer(swclk, swdio, target, reset_pin=reset_pin,
                    reset_hold=reset_hold, reset_delay=reset_delay, **kwargs) as programmer:
        return programmer.program(filename, address=address, verify=verify,
                                  reset=reset, progress=progress, status=status)
